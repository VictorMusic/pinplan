def _slug(t):
    t = normalize(t or "").lower().strip()
    for a, b in (("á","a"),("é","e"),("í","i"),("ó","o"),("ú","u"),("ü","u"),("ñ","n")):
        t = t.replace(a, b)
    return re.sub(r"[^a-z0-9 ]", "", t).strip()

# Nombres y alias de salas: si el "titulo" es solo eso, es un enlace a la sala, no un concierto
_SALA_SLUGS = set()
for _s in _SALAS:
    _SALA_SLUGS.add(_slug(_s.get("nombre", "")))
    for _kw in _s.get("keywords", []):
        _SALA_SLUGS.add(_slug(_kw))
_SALA_SLUGS.discard("")

# Rutas de taxonomia (lugares, categorias, etiquetas): son fichas de sala o de
# seccion, nunca un concierto concreto. aragonmusical.com/lugares/... es el caso tipico.
JUNK_URL_PARTS = (
    "/lugares/", "/lugar/", "/venue/", "/venues/", "/salas/", "/sala/",
    "/categoria/", "/category/", "/tag/", "/etiqueta/", "/author/", "/autor/",
)

def is_junk_url(url):
    low = (url or "").lower()
    return any(part in low for part in JUNK_URL_PARTS)

def is_junk_title(titulo):
    sl = _slug(titulo)
    if len(sl) < 3: return True
    if sl in JUNK_TITLES: return True
    if sl in _SALA_SLUGS: return True
    if re.fullmatch(r"(ver|abrir|mira)( .{0,20})?", sl): return True
    return False

def make_event(titulo, fecha, hora, sala, url, imagen="", descripcion=""):
    return {
        "titulo": normalize(titulo),
        "fecha": fecha or "",
        "hora": hora or "",
        "sala": normalize_sala(normalize(sala)),
        "url": url or "",
        "imagen": imagen or "",
        "descripcion": normalize(descripcion),
    }

def extract_tribe(soup, sala_default, base_url):
    events = []
    articles = []
    for sel in ["article.type-tribe_events","article.tribe_events_cat",
                ".tribe-events-calendar-list__event",".tribe-events-loop article",
                "article[class*='tribe']",".events-archive article"]:
        items = soup.select(sel)
        if items: articles = items; break
    for art in articles:
        title_el = art.select_one("h2 a, h3 a, .entry-title a, .tribe-events-list-event-title a")
        # Try multiple date selectors aggressively
        date_el = art.select_one(
            "time[datetime], abbr[title], .tribe-event-date-start, "
            "[class*='tribe-event-date'], [class*='event-date'], "
            "[class*='date-start'], .entry-date, .published"
        )
        loc_el = art.select_one(".tribe-venue, [class*='tribe-venue'], [class*='venue']")
        img_el = art.select_one("img")
        link_el = art.select_one("a[href]")
        title = normalize(title_el.get_text()) if title_el else ""
        if not title or len(title) < 3: continue
        
        # Get date from multiple sources
        fecha_raw = ""
        if date_el:
            fecha_raw = (date_el.get("datetime","") or 
                        date_el.get("title","") or 
                        date_el.get("content","") or 
                        date_el.get_text())
        
        # Also check link URL for date pattern (many WP sites have /2025/05/15/ in URL)
        if not parse_date(fecha_raw) and link_el:
            href_date = link_el.get("href","")
            m = re.search(r"/(202[0-9])/(\d{2})/(\d{2})/", href_date)
            if m:
                fecha_raw = f"{m.group(1)}-{m.group(2)}-{m.group(3)}"
        
        hora_el = art.select_one("[class*='time'], .tribe-events-schedule, [class*='hora']")
        hora_raw = hora_el.get_text() if hora_el else fecha_raw
        sala = normalize(loc_el.get_text()) if loc_el else sala_default
        href = link_el["href"] if link_el else base_url
        if href and not href.startswith("http"): href = base_url.rstrip("/") + "/" + href.lstrip("/")
        img = (img_el.get("src","") or img_el.get("data-src","")) if img_el else ""
        events.append(make_event(title, parse_date(fecha_raw) or "", parse_time(hora_raw), sala or sala_default, href, img))
    return events


def _jsonld_bloques(texto):
    for bruto in re.findall(r"<script[^>]+application/ld\+json[^>]*>(.*?)</script>", texto, re.S):
        try:
            yield json.loads(_html.unescape(bruto.strip()))
        except Exception:
            continue

def _jsonld_eventos(dato):
    """Recorre el arbol JSON-LD y devuelve los nodos de tipo Event."""
    if isinstance(dato, list):
        for d in dato:
            yield from _jsonld_eventos(d)
    elif isinstance(dato, dict):
        if "Event" in str(dato.get("@type", "")):
            yield dato
        for clave in ("@graph", "itemListElement", "item", "subEvent"):
            if clave in dato:
                yield from _jsonld_eventos(dato[clave])

def scrape_jsonld(url, nombre_fuente, solo_zaragoza=True):
    """Lee la agenda de los datos estructurados schema.org de la pagina.

    Es mas estable que raspar el HTML: el marcado cambia de diseno a menudo, el
    JSON-LD casi nunca, y trae fecha con hora, sala y localidad ya separadas.
    """
    r = get(url)
    if not r:
        print(f"  {nombre_fuente}: sin respuesta")
        return []
    evs, fuera = [], 0
    for bloque in _jsonld_bloques(r.text):
        for ev in _jsonld_eventos(bloque):
            titulo = normalize(str(ev.get("name") or ""))
            inicio = str(ev.get("startDate") or "")
            if not titulo or len(titulo) < 3 or not inicio: continue
            fecha = parse_date(inicio[:10]) or ""
            hora = ""
            mh = re.search(r"T(\d{2}):(\d{2})", inicio)
            if mh and mh.group(0) != "T00:00":
                hora = f"{mh.group(1)}:{mh.group(2)}"
            lugar = ev.get("location") or {}
            sala = normalize(str(lugar.get("name") or "")) if isinstance(lugar, dict) else ""
            ciudad = ""
            if isinstance(lugar, dict):
                dirn = lugar.get("address")
                if isinstance(dirn, dict): ciudad = str(dirn.get("addressLocality") or "")
                elif isinstance(dirn, str): ciudad = dirn
            if solo_zaragoza and not _es_zaragoza_ciudad(ciudad, sala):
                fuera += 1
                continue
            enlace = str(ev.get("url") or url)
            imagen = ev.get("image")
            if isinstance(imagen, list): imagen = imagen[0] if imagen else ""
            if isinstance(imagen, dict): imagen = imagen.get("url", "")
            evs.append(make_event(titulo, fecha, hora, sala or "Zaragoza", enlace, str(imagen or "")))
    con_hora = sum(1 for e in evs if e["hora"])
    print(f"  {nombre_fuente}: {len(evs)} ({con_hora} con hora, {fuera} fuera de la ciudad)")
    return evs

