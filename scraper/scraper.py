def normalize(t):
    if not t: return ""
    # Decode HTML entities (e.g. &#8211; -> —, &amp; -> &)
    import html
    t = html.unescape(str(t))
    return " ".join(t.split()).strip()

def parse_date(text):
    if not text: return None
    t = text.lower().strip()
    m = re.search(r'(\d{4})-(\d{2})-(\d{2})', t)
    if m: return m.group(0)
    m = re.search(r'(\d{1,2})/(\d{1,2})/(\d{4})', t)
    if m: return f"{m.group(3)}-{int(m.group(2)):02d}-{int(m.group(1)):02d}"
    m = re.search(r'(\d{1,2})\s+(?:de\s+)?(\w+)\s+(?:de\s+)?(\d{4})', t)
    if m:
        mon = MONTHS.get(m.group(2)[:3])
        if mon: return f"{m.group(3)}-{mon:02d}-{int(m.group(1)):02d}"
    m = re.search(r'(\d{1,2})\s+(?:de\s+)?(\w+)', t)
    if m:
        mon = MONTHS.get(m.group(2)[:3])
        if mon:
            y = date.today().year
            d = int(m.group(1))
            candidate = f"{y}-{mon:02d}-{d:02d}"
            if candidate < date.today().isoformat():
                candidate = f"{y+1}-{mon:02d}-{d:02d}"
            return candidate
    return None

def parse_time(text):
    if not text: return ""
    m = re.search(r'(\d{1,2})[:\.](\d{2})', text)
    if m: return f"{int(m.group(1)):02d}:{m.group(2)}"
    return ""

def get(url, timeout=(20, 25), retries=2):
    """GET con reintentos, espera creciente y registro de diagnostico por dominio.

    timeout es (conexion, lectura). Con 8 s de conexion el job bajaba mucho de
    duracion, pero aragonenvivo.com tarda mas que eso en aceptar la conexion desde
    el runner de GitHub y se perdia entera: 20 s deja margen y aun asi un host
    muerto cuesta ~45 s en vez de los 95 s de antes.
    """
    dom = re.sub(r"^www\.", "", (url.split("/")[2] if "://" in url else url))
    last = ""
    for attempt in range(retries):
        t0 = time.time()
        try:
            r = SESSION.get(url, timeout=timeout, allow_redirects=True)
            ms = int((time.time() - t0) * 1000)
            if r.status_code >= 400:
                last = f"HTTP {r.status_code}"
                DIAG[dom] = {"estado": last, "ms": ms, "bytes": len(r.content)}
                # 404/410 no se arreglan reintentando: la URL ya no existe
                if r.status_code in (404, 410):
                    print(f"  WARN {url[:70]}: {last} (URL inexistente, no reintento)")
                    return None
            else:
                blocked = _looks_blocked(r.text)
                if blocked:
                    last = f"muro anti-bot ({blocked!r})"
                    DIAG[dom] = {"estado": last, "ms": ms, "bytes": len(r.content)}
                else:
                    DIAG[dom] = {"estado": "OK", "ms": ms, "bytes": len(r.content)}
                    return r
        except Exception as e:
            ms = int((time.time() - t0) * 1000)
            last = f"{type(e).__name__}: {str(e)[:90]}"
            DIAG[dom] = {"estado": last, "ms": ms, "bytes": 0}
        if attempt < retries - 1:
            time.sleep(2 ** attempt + random.uniform(0, 1.2))
    print(f"  WARN {url[:70]}: {last}")
    return None

