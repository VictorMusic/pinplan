def _am_campo(desc, etiqueta):
    """Extrae un campo del bloque '<strong>Etiqueta:</strong> valor <br />'."""
    m = re.search(r"<strong>\s*%s\s*:?\s*</strong>(.*?)<br" % etiqueta, desc, re.S | re.I)
    if not m: return ""
    return normalize(re.sub(r"<[^>]+>", " ", m.group(1)))

